    public function __construct()
    {
        parent::__construct();

        $env = static function (array $keys, $default = null, bool $trimQuotes = false) {
            foreach ($keys as $key) {
                $value = getenv($key);
                if ($value === false || $value === '') {
                    continue;
                }

                if ($trimQuotes) {
                    $length = strlen($value);
                    if ($length >= 2) {
                        $first = $value[0];
                        $last = $value[$length - 1];
                        if (($first === '"' && $last === '"') || ($first === "'" && $last === "'")) {
                            $value = substr($value, 1, -1);
                        }
                    }
                }

                return $value;
            }

            return $default;
        };

        $this->default['hostname'] = (string) $env(['database.default.hostname', 'DB_HOSTNAME', 'DB_HOST'], $this->default['hostname'], true);
        $this->default['username'] = (string) $env(['database.default.username', 'DB_USERNAME', 'DB_USER'], $this->default['username'], true);
        $this->default['password'] = (string) $env(['database.default.password', 'DB_PASSWORD', 'DB_PASS'], $this->default['password'], true);
        $this->default['database'] = (string) $env(['database.default.database', 'DB_DATABASE', 'DB_NAME'], $this->default['database'], true);
        $this->default['port'] = (int) $env(['database.default.port', 'DB_PORT'], $this->default['port']);
        $this->default['DBDriver'] = (string) $env(['database.default.DBDriver', 'DB_DRIVER'], $this->default['DBDriver'], true);
        $this->default['DBDebug'] = filter_var($env(['database.default.DBDebug', 'DB_DEBUG'], $this->default['DBDebug']), FILTER_VALIDATE_BOOLEAN);
        $this->default['pConnect'] = filter_var($env(['database.default.pConnect', 'DB_PCONNECT'], $this->default['pConnect']), FILTER_VALIDATE_BOOLEAN);
        $this->default['encrypt'] = filter_var($env(['database.default.encrypt', 'DB_ENCRYPT'], $this->default['encrypt']), FILTER_VALIDATE_BOOLEAN);
        $this->default['strictOn'] = filter_var($env(['database.default.strictOn', 'DB_STRICT_ON'], $this->default['strictOn']), FILTER_VALIDATE_BOOLEAN);

        // Ensure that we always set the database group to 'tests' if
        // we are currently running an automated test suite, so that
        // we don't overwrite live data on accident.
        if (ENVIRONMENT === 'testing') {
            $this->defaultGroup = 'tests';
        }
    }
